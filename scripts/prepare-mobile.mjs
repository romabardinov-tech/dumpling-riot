import { mkdir, readFile, writeFile, copyFile, rm } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const out=resolve(root,'www');
const files=['manifest.webmanifest','privacy.html','icon-v38-180.png','icon-v38-192.png','icon-v38-512.png'];
const source=await readFile(resolve(root,'index.html'),'utf8');
const peer='https://unpkg.com/peerjs@1.5.4/dist/peerjs.min.js';
if(source.split(peer).length!==2)throw Error('Peer library URL changed');
const html=source.replace(peer,'./vendor/peerjs.min.js');
const peerFile=resolve(root,'node_modules/peerjs/dist/peerjs.min.js');
await readFile(peerFile);
for(const name of files)await readFile(resolve(root,name));
await rm(out,{recursive:true,force:true});
await mkdir(resolve(out,'vendor'),{recursive:true});
for(const name of files)await copyFile(resolve(root,name),resolve(out,name));
await copyFile(peerFile,resolve(out,'vendor/peerjs.min.js'));
await copyFile(resolve(root,'node_modules/peerjs/LICENSE'),resolve(out,'vendor/peerjs-LICENSE.txt'));
await writeFile(resolve(out,'index.html'),html);
console.log('Native web assets prepared locally in www/; no remote game URL.');
